package com.roadaccident.controller;

import com.roadaccident.model.Prediction;
import com.roadaccident.service.PredictionService;
import jakarta.validation.Valid;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.http.*;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

import java.io.IOException;
import java.nio.file.*;
import java.util.List;
import java.util.Map;

/**
 * REST controller — exposes all endpoints under /api.
 *
 * Spring MVC note:
 *   @RestController = @Controller + @ResponseBody (returns JSON by default).
 *   Spring's DispatcherServlet routes incoming HTTP requests here.
 *   This is the "Controller" layer in the MVC pattern.
 */
@RestController
@RequestMapping("/api")
public class PredictionController {

    @Autowired
    private PredictionService service;

    /** Absolute path to the reports directory (set in application.properties) */
    @Value("${reports.absolute.path}")
    private String reportsDir;

    /** Absolute path to options.json (set in application.properties) */
    @Value("${options.file.path}")
    private String optionsFilePath;

    // ── POST /api/predictions ────────────────────────────────────────────────
    /**
     * Accepts validated input, calls the ML service, saves and returns 201.
     * @Valid triggers Bean Validation on the Prediction entity.
     */
    @PostMapping("/predictions")
    public ResponseEntity<Prediction> create(@Valid @RequestBody Prediction prediction) {
        Prediction saved = service.predictAndSave(prediction);
        return ResponseEntity.status(HttpStatus.CREATED).body(saved);
    }

    // ── GET /api/predictions?severity=minor ───────────────────────────────────
    /**
     * List all predictions, or filter by severity via optional query parameter.
     * The HQL query in PredictionRepository handles the filtering.
     */
    @GetMapping("/predictions")
    public List<Prediction> list(@RequestParam(required = false) String severity) {
        return service.findAll(severity);
    }

    // ── GET /api/predictions/{id} ─────────────────────────────────────────────
    /** Fetch a single record; returns 404 if not found. */
    @GetMapping("/predictions/{id}")
    public Prediction getById(@PathVariable Long id) {
        return service.findById(id);
    }

    // ── PUT /api/predictions/{id} ─────────────────────────────────────────────
    /** Update input fields, re-run prediction, save and return updated record. */
    @PutMapping("/predictions/{id}")
    public Prediction update(@PathVariable Long id,
                             @Valid @RequestBody Prediction updated) {
        return service.updateAndRepredict(id, updated);
    }

    // ── DELETE /api/predictions/{id} ──────────────────────────────────────────
    /** Delete a record; returns 204 No Content. */
    @DeleteMapping("/predictions/{id}")
    public ResponseEntity<Void> delete(@PathVariable Long id) {
        service.delete(id);
        return ResponseEntity.noContent().build();
    }

    // ── GET /api/model/metrics ────────────────────────────────────────────────
    /**
     * Returns the contents of reports/metrics.json as a JSON object.
     * The frontend ModelInfoPage reads this to display accuracy, F1, etc.
     */
    @GetMapping("/model/metrics")
    public ResponseEntity<Object> getMetrics() throws IOException {
        Path metricsPath = Path.of(reportsDir, "metrics.json");
        if (!Files.exists(metricsPath)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND,
                    "metrics.json not found — run train.py first");
        }
        String json = Files.readString(metricsPath);
        // Parse and return as a Map so Spring serializes it properly
        com.fasterxml.jackson.databind.ObjectMapper mapper = new com.fasterxml.jackson.databind.ObjectMapper();
        Object parsed = mapper.readValue(json, Object.class);
        return ResponseEntity.ok(parsed);
    }

    // ── GET /api/options ──────────────────────────────────────────────────────
    /**
     * Returns valid dropdown values for all categorical fields.
     * Generated by train.py as ml-service/options.json.
     * The frontend reads this to build select dropdowns.
     */
    @GetMapping("/options")
    public ResponseEntity<Object> getOptions() throws IOException {
        Path optPath = Path.of(optionsFilePath);
        if (!Files.exists(optPath)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND,
                    "options.json not found — run train.py first");
        }
        String json = Files.readString(optPath);
        com.fasterxml.jackson.databind.ObjectMapper mapper = new com.fasterxml.jackson.databind.ObjectMapper();
        Object parsed = mapper.readValue(json, Object.class);
        return ResponseEntity.ok(parsed);
    }

    // ── GET /api/reports/{filename} ───────────────────────────────────────────
    /**
     * Serves chart images from the reports directory.
     * The frontend embeds these in the Model Info page.
     * Only .png and .json files are served (basic security guard).
     */
    @GetMapping("/reports/{filename}")
    public ResponseEntity<Resource> getReport(@PathVariable String filename) {
        // Basic guard: only allow alphanumeric names with safe extensions
        if (!filename.matches("[\\w\\-]+\\.(png|json)")) {
            return ResponseEntity.badRequest().build();
        }
        Path filePath = Path.of(reportsDir, filename);
        if (!Files.exists(filePath)) {
            return ResponseEntity.notFound().build();
        }
        Resource resource = new FileSystemResource(filePath.toFile());
        String contentType = filename.endsWith(".png") ? "image/png" : "application/json";
        return ResponseEntity.ok()
                .contentType(MediaType.parseMediaType(contentType))
                .body(resource);
    }
}
